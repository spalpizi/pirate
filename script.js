  function readWindowCartRaw() {
    try {
      const name = String(window.name || "");
      const re = new RegExp(`(?:^|;)${CART_WINDOW_FALLBACK_KEY}=([^;]*)`);
      const m = name.match(re);
      if (!m || !m[1]) return null;
      return decodeURIComponent(m[1]);
    } catch {
      return null;
    }
  }

  function writeWindowCartRaw(raw) {
    try {
      const encoded = encodeURIComponent(raw);
      const token = `${CART_WINDOW_FALLBACK_KEY}=${encoded}`;
      const current = String(window.name || "");
      const re = new RegExp(`(?:^|;)${CART_WINDOW_FALLBACK_KEY}=[^;]*`);
      window.name = re.test(current) ? current.replace(re, token) : (current ? `${current};${token}` : token);
    } catch {
      // no-op
    }
  }

  function normalizeCartItems(arr) {
    if (!Array.isArray(arr)) return [];
    const merged = new Map();
    arr.forEach((it) => {
      const normalized = {
        id: String(it.id || ""),
        variant: normalizeVariant(it.variant || {}),
        qty: Math.max(1, Number(it.qty || 1))
      };
      if (!normalized.id || !CATALOG[normalized.id]) return;

      const key = lineKey(normalized.id, normalized.variant);
      const existing = merged.get(key);
      if (existing) {
        existing.qty += normalized.qty;
        return;
      }
      merged.set(key, normalized);
    });
    return Array.from(merged.values());
  }

  function updateInternalCartLinks() {
    document.querySelectorAll("a[href]").forEach((a) => {
      const href = a.getAttribute("href");
      if (!href || href.startsWith("#") || href.startsWith("mailto:") || href.startsWith("tel:") || href.startsWith("javascript:")) return;

      let url;
      try {
        url = new URL(href, window.location.href);
      } catch {
        return;
      }
      if (!/\.html$/i.test(url.pathname)) return;
      url.searchParams.delete("_cart");

      a.setAttribute("href", url.pathname + url.search + url.hash);
    });
  }

  function clearLegacyCartUrlParam() {
    if (!window.history.replaceState) return;
    try {
      const url = new URL(window.location.href);
      if (!url.searchParams.has("_cart")) return;
      url.searchParams.delete("_cart");
      window.history.replaceState(null, "", url.pathname + url.search + url.hash);
    } catch {
      // no-op
    }
  }

  function normalizeVariant(v) {
    const out = {};
    if (!v || typeof v !== "object") return out;
    for (const [k, val] of Object.entries(v)) {
      if (val === null || val === undefined) continue;
      const s = String(val).trim();
      if (!s) continue;
      out[k] = s;
    }
    return out;
  }

  function bootstrapCartSession() {
    if (safeSessionGet(CART_SESSION_BOOT_KEY)) return;
    safeSessionSet(CART_SESSION_BOOT_KEY, "1");
    safeSessionSet(CART_KEY_V2, "[]");
    safeLocalRemove(CART_KEY_V2);
    safeLocalRemove(CART_KEY_V1);
    writeWindowCartRaw("[]");
    clearLegacyCartUrlParam();
    updateInternalCartLinks();
  }

  function lineKey(id, variant) {
    const v = normalizeVariant(variant);
    const keys = Object.keys(v).sort();
    const sig = keys.map(k => `${k}=${v[k]}`).join(";");
    return `${id}|${sig}`;
  }

  function readCartV2() {
    try {
      const raw = safeSessionGet(CART_KEY_V2) || readWindowCartRaw();
      if (!raw) return null;
      return normalizeCartItems(JSON.parse(raw));
    } catch {
      return null;
    }
  }

  function writeCartV2(items) {
    const normalized = normalizeCartItems(items);
    const raw = JSON.stringify(normalized);
    safeSessionSet(CART_KEY_V2, raw);
    writeWindowCartRaw(raw);
    updateInternalCartLinks();
  }

  function readCart() {
    bootstrapCartSession();
    return readCartV2() || [];
  }

  function cartCount(items) {
    return items.reduce((sum, it) => sum + (it.qty || 0), 0);
  }

  function cartSubtotal(items) {
    return items.reduce((sum, it) => {
      const p = CATALOG[it.id];
      if (!p) return sum;
      return sum + p.priceEUR * it.qty;
    }, 0);
  }

  function upsertLine(items, id, variant, qtyDelta) {
    const v = normalizeVariant(variant);
    const key = lineKey(id, v);
    const idx = items.findIndex(it => lineKey(it.id, it.variant) === key);
    if (idx >= 0) {
      items[idx].qty = Math.max(1, items[idx].qty + qtyDelta);
      return items;
    }
    items.push({ id, variant: v, qty: Math.max(1, qtyDelta) });
    return items;
  }

  function setLineQty(items, key, newQty) {
    const idx = items.findIndex(it => lineKey(it.id, it.variant) === key);
    if (idx < 0) return items;
    const q = Number(newQty || 1);
    if (q <= 0) items.splice(idx, 1);
    else items[idx].qty = Math.max(1, q);
    return items;
  }

  function incLine(items, key) {
    const idx = items.findIndex(it => lineKey(it.id, it.variant) === key);
    if (idx < 0) return items;
    items[idx].qty += 1;
    return items;
  }

  function decLine(items, key) {
    const idx = items.findIndex(it => lineKey(it.id, it.variant) === key);
    if (idx < 0) return items;
    items[idx].qty -= 1;
    if (items[idx].qty <= 0) items.splice(idx, 1);
    return items;
  }

