  // Mark current page in drawer navigation.
  (function markCurrentMenuLink() {
    function normalizePath(pathname) {
      const clean = pathname.replace(/\/index\.html$/, "/").replace(/\/+$/, "/");
      return clean === "" ? "/" : clean;
    }

    function menuKey(url) {
      const path = normalizePath(url.pathname);
      if (!/\/category\.html$/.test(path)) return path;
      const category = (url.searchParams.get("category") || "").trim();
      return `${path}?category=${category}`;
    }

    const currentUrl = new URL(window.location.href);
    const current = menuKey(currentUrl);
    document.querySelectorAll(".menu-link").forEach((link) => {
      const href = link.getAttribute("href");
      if (!href) return;

      let url;
      try {
        url = new URL(href, window.location.href);
      } catch {
        return;
      }
      const isCurrent = menuKey(url) === current;

      if (isCurrent) {
        link.setAttribute("aria-current", "page");
        const small = link.querySelector("small");
        if (small) small.textContent = "Sei qui";
      } else {
        link.removeAttribute("aria-current");
      }
    });
  })();

  (function initRevealAnimations() {
    const revealEls = Array.from(document.querySelectorAll("[data-reveal]"));
    if (!revealEls.length) return;

    const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    const showNow = (el) => {
      el.classList.add("is-visible");
      el.style.transitionDelay = "";
    };

    if (reduceMotion || !("IntersectionObserver" in window)) {
      revealEls.forEach(showNow);
      return;
    }

    const observer = new IntersectionObserver((entries, obs) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        const el = entry.target;
        const delay = Number(el.getAttribute("data-reveal-delay") || 0);
        if (delay > 0) el.style.transitionDelay = `${delay}ms`;
        el.classList.add("is-visible");
        obs.unobserve(el);
      });
    }, { threshold: 0.16, rootMargin: "0px 0px -8% 0px" });

    revealEls.forEach((el) => observer.observe(el));
  })();

